-- Seasonal quest classification follows https://runescape.wiki/w/Seasonal_quests.
local seasonalQuests = {
    ["It's Snow Bother"] = true,
    ["Great Egg-spectations"] = true,
    ["Field of Screams"] = true,
    ["A Christmas Reunion"] = true,
    ["Guys and Dolls"] = true,
