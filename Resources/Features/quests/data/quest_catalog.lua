-- These miniquests lack the suffix used by the other bundled entries.
local miniquests = { [461] = true, [462] = true }
local records = {}
for _, tuple in ipairs(tuples) do
    local prerequisites, skills = {}, {}
    for _, questID in ipairs(tuple[3]) do
        prerequisites[#prerequisites + 1] = { id = questID }
    end
    for _, skill in ipairs(tuple[4]) do
        skills[#skills + 1] = {
            id = skill[1],
            name = SkillCatalog.byID[skill[1]].name,
            minimumLevel = skill[2],
        }
    end
    records[#records + 1] = {
        id = tuple[1],
        name = tuple[2],
        isMiniquest = miniquests[tuple[1]] == true
            or string.find(tuple[2], "(miniquest)", 1, true) ~= nil
            or string.find(tuple[2], "(saga)", 1, true) ~= nil,
        isSeasonalQuest = seasonalQuests[tuple[2]] == true,
        preReqQuests = prerequisites,
        preReqSkills = skills,
    }
end
return { records = records }
